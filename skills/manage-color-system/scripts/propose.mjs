#!/usr/bin/env node
// propose: build a themed token set from palettes and a role recipe, solving each tone for its contrast target.
// Usage: node propose.mjs <recipe.json> [--out tokens.css] [--json out.json]
// Every contrast figure written into the CSS notes is measured, never typed.
import fs from 'node:fs';
import { paletteFrom, fitTone, wcag, apca, hct, harmonize, over, tone } from './color-steward.mjs';
import { argbFromHex, hexFromArgb, Hct } from './vendor/deps.mjs';

const [file, ...a] = process.argv.slice(2);
const flag = n => { const i = a.indexOf(n); return i >= 0 ? a[i + 1] : null; };
const recipe = JSON.parse(fs.readFileSync(file, 'utf8'));

// Palettes: { name: { hue, chroma } | { seed: '#hex' } | { seed, harmonizeTo: '#hex' } }
const pals = {};
for (const [name, p] of Object.entries(recipe.palettes)) {
  let hue = p.hue, chroma = p.chroma;
  if (p.seed) { const src = p.harmonizeTo ? harmonize(p.seed, p.harmonizeTo) : p.seed; const h = Hct.fromInt(argbFromHex(src)); hue = h.hue; chroma = p.chroma ?? h.chroma; }
  pals[name] = paletteFrom(hue, chroma);
}
const r2 = n => Math.round(n * 100) / 100;
const out = { levels: {} }; const unsolvedList = [];
for (const level of recipe.levels) {               // e.g. standard, high
  for (const theme of ['day', 'night']) {
    const key = `${theme}${level.name === 'standard' ? '' : '-' + level.name}`; const v = {}; const notes = {};
    for (const r of recipe.roles) {
      const spec = r[theme]; if (!spec) continue;
      const pal = pals[spec.palette || r.palette];
      if (spec.alpha != null) { // state layers and scrims: a color at an opacity
        const base = spec.of ? v[spec.of] : hexFromArgb(pal.tone(spec.tone));
        v[r.token] = `${base}${Math.round(spec.alpha * 255).toString(16).padStart(2, '0')}`;
        notes[r.token] = `${r.use} ${Math.round(spec.alpha * 100)}% of ${spec.of || 'tone ' + spec.tone}.`;
        continue;
      }
      const target = { ...(spec.target || {}) };
      if (level.boost && target.wcag) target.wcag = Math.max(target.wcag, level.boost[r.kind] ?? target.wcag);
      if (level.boost && target.apca) target.apca = Math.max(target.apca, level.boostApca?.[r.kind] ?? target.apca);
      if (spec.pin) { v[r.token] = spec.pin; notes[r.token] = `${r.use} Pinned brand value.`; continue; }
      const prefer = level.name !== 'standard' && spec[`prefer_${level.name}`] != null ? spec[`prefer_${level.name}`] : spec.prefer;
      let pick;
      if (spec.against && Object.keys(target).length) {
        const bgs = [].concat(spec.against).map(b => v[b]);
        // satisfy every listed ground: tighten until all pass
        pick = null;
        if (bgs.some(b => !b)) throw new Error(`${key} ${r.token}: ground missing in ${[].concat(spec.against).join(",")}`);
        const dir = spec.direction || (tone(bgs[0]) > 50 ? -1 : 1);
        for (let step = 0; step <= 200 && !pick; step++) {
          const c = fitTone(pal, bgs[0], target, prefer + dir * step * 0.5);
          if (c && bgs.every(b => wcag(c.hex, b) >= (target.wcag ?? 0) && Math.abs(apca(c.hex, b)) >= (target.apca ?? 0))) pick = c;
        }
      } else pick = { tone: spec.prefer, hex: hexFromArgb(pal.tone(spec.prefer)) };
      if (!pick && spec.against) { // best effort: the tone with the highest worst-case contrast, reported
        const bgs = [].concat(spec.against).map(b => v[b]); let best = null;
        for (let t = 0; t <= 100; t += 0.5) { const hex = hexFromArgb(pal.tone(t)); const worst = Math.min(...bgs.map(b => wcag(hex, b)));
          if (!best || worst > best.worst) best = { tone: t, hex, worst }; }
        pick = best; unsolvedList.push(`${key}:${r.token} (best ${r2(best.worst)}:1)`);
      }
      if (!pick) { notes[r.token] = 'UNSOLVED'; continue; }
      v[r.token] = pick.hex;
      const meas = [].concat(spec.against || []).map(b => `${r2(wcag(pick.hex, v[b]))}:1, Lc ${Math.round(Math.abs(apca(pick.hex, v[b])))} on ${b}`).join('; ');
      notes[r.token] = `${r.use} ${spec.palette || r.palette} tone ${pick.tone}.${meas ? ' ' + meas + '.' : ''}`;
    }
    out.levels[key] = { values: v, notes };
  }
}
// CSS: day is the default (reading pages), night under data-theme="dark"; high contrast under data-contrast="high"
const aliasLines = theme => { const al = { ...(recipe.aliases?.both || {}), ...(recipe.aliases?.[theme] || {}) };
  return Object.entries(al).map(([a, t]) => `  --${a}: var(--${t}); /* Alias: older Bearing name. */`); };
const block = (sel, k, withAliases) => `${sel} {\n${[...Object.entries(out.levels[k].values).map(([t, h]) => `  --${t}: ${h}; /* ${out.levels[k].notes[t]} */`), ...(withAliases ? aliasLines(k.startsWith('day') ? 'day' : 'night') : [])].join('\n')}\n}`;
const css = [`/* ${recipe.name}: generated by color-steward propose.mjs. Do not edit values by hand; edit the recipe and rerun. */`,
  block(':root, [data-theme="light"]', 'day', true), block('[data-theme="dark"]', 'night', true),
  ...(out.levels['day-high'] ? [block('[data-contrast="high"], [data-theme="light"][data-contrast="high"]', 'day-high'), block('[data-theme="dark"][data-contrast="high"]', 'night-high')] : [])].join('\n');
out.palettes = Object.fromEntries(Object.entries(pals).map(([n, p]) => [n, Object.fromEntries([0, 4, 6, 8, 10, 12, 17, 20, 22, 30, 40, 50, 60, 70, 80, 87, 90, 92, 94, 95, 96, 98, 100].map(t => [t, hexFromArgb(p.tone(t))]))]));
if (flag('--out')) fs.writeFileSync(flag('--out'), css + '\n');
if (flag('--json')) fs.writeFileSync(flag('--json'), JSON.stringify(out, null, 2));
if (!flag('--out') && !flag('--json')) console.log(css);
out.bestEffort = unsolvedList;
if (unsolvedList.length) { console.error('Targets not met, best effort used:', unsolvedList.join(', ')); process.exitCode = 2; }
