#!/usr/bin/env python3
"""sync_wordlists.py - derive scan.py's vocabulary from rewrite_scan.py.

rewrite_scan.py is the single authoritative home for every word and
phrase list in the rewrite scanner. scan.py, the audit and score engine, wants the
same vocabulary in a different shape: plain stemmed terms in `wordlists/*.txt`
rather than regexes.

Two hand-maintained copies of one vocabulary is exactly the drift this house is
organised to prevent, so the txt files are generated from rewrite_scan and never
edited by hand. The selftest regenerates them in memory and fails if they differ
from what is on disk, which means the copy cannot silently rot.

    python3 sync_wordlists.py            # rewrite the generated lists
    python3 sync_wordlists.py --check    # exit 1 if they are out of date

Only `vocabulary.txt` and `flowery-phrases.txt` are generated. The weighted lists
(`marketing-verbs.txt`, `soft-phrasing.txt`) carry per-term weights that rewrite_scan
has no equivalent for, so they stay hand-maintained and are left alone.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
WORDLISTS = HERE.parent / "wordlists"

sys.path.insert(0, str(HERE))
import rewrite_scan  # noqa: E402

# The two vocabulary categories. Severity is rewrite_scan's business; scan.py
# reports position and density and does not grade, so both feed one list.
SOURCE_CATEGORIES = ("banned vocabulary", "review vocabulary (judge each use)")

HEADER = (
    "# GENERATED by scripts/sync_wordlists.py from rewrite_scan.py. Do not edit.\n"
    "# rewrite_scan.py is the single authoritative home for house vocabulary.\n"
    "# Add or retire terms there, then re-run the generator.\n"
)


def shortest_literal(rx: str) -> str:
    """The shortest string a rewrite_scan vocabulary regex matches.

    These regexes are a narrow, known family (word-boundary anchored, with
    optional suffix groups and simple alternations), not arbitrary patterns, so
    reducing them literally is safe here and would not be in general.
    """
    s = re.sub(r"^\\b|\\b$", "", rx)
    s = re.sub(r"\[[^\]]*\]\?", "", s)              # [sd]?   -> ""
    s = re.sub(r"\([^)]*\)\?", "", s)               # (ally)? -> ""
    s = re.sub(r"\(([^)|]*)\|[^)]*\)", r"\1", s)    # (a|b)   -> a
    s = re.sub(r"\(([^)]*)\)", r"\1", s)            # (a)     -> a
    s = re.sub(r"\[[^\]]*\]", "", s).replace("\\", "").replace("?", "")
    return re.sub(r"\s+", " ", s.replace(".", " ")).strip()


def derive() -> dict:
    """-> {filename: full file text}. Single words become vocabulary, multi-word
    terms become phrases, because scan.py's stem-set loader splits on words and
    would otherwise match each half of a phrase on its own."""
    words, phrases = set(), set()
    for category in SOURCE_CATEGORIES:
        patterns = next((p for c, _sev, p in rewrite_scan.PATTERNS if c == category), None)
        if patterns is None:
            raise SystemExit(f"rewrite_scan.PATTERNS no longer has a {category!r} category. "
                             "Update SOURCE_CATEGORIES in sync_wordlists.py.")
        for rx in patterns:
            term = shortest_literal(rx)
            if not term:
                continue
            (phrases if " " in term else words).add(term)
    return {
        "vocabulary.txt": HEADER + "\n".join(sorted(words)) + "\n",
        "flowery-phrases.txt": HEADER + "\n".join(sorted(phrases)) + "\n",
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the generated lists are out of date")
    args = ap.parse_args()

    WORDLISTS.mkdir(exist_ok=True)
    stale = []
    for name, text in derive().items():
        path = WORDLISTS / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        stale.append(name)
        if not args.check:
            path.write_text(text, encoding="utf-8")

    if args.check:
        if stale:
            print(f"STALE: {', '.join(stale)} differ from rewrite_scan.py. "
                  "Run sync_wordlists.py.")
            return 1
        print("wordlists are in sync with rewrite_scan.py")
        return 0

    print(f"rewrote {len(stale)} file(s): {', '.join(stale) or 'none, already current'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
